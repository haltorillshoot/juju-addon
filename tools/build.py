#!/usr/bin/env python3
"""Bundle src/*.lua into ONE file: dist/jhc_hood_customs.lua

The Juju docs do not document multi-file addons, so the shipped addon is a single script.
Each module becomes `__defs["name"] = function(require) <file> end` with a tiny local require.
Usage: python tools/build.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDER = ["util", "config", "host", "diag", "weapon", "engine", "automode", "world", "ui", "main"]

HEADER = """--[[
  JHC Hit Checker for Juju (Hood Customs)   v{version}
  Single-file bundle generated by tools/build.py - edit src/*.lua, not this file.

  WHAT IT DOES
    * Hit Checker: counts shot attempts, CONFIRMED hits (server-replicated damage on another
      player), misses (no damage on a healthy connection), unconfirmed and not-fired shots.
    * Connection diagnostics from the documented API only: juju.get_ping(), server/client
      CFrame gap; derives jitter, spikes, stalls and an adaptive confirmation window.
    * Double Barrel Shotgun identification + Auto Mode tracking profile (it does NOT fire).
    * Read-only towards Juju: never calls set_*/add_*/remove_*/purchase_item/load_config and only
      writes flags named jhc_*.

  WHAT IT CANNOT DO (not exposed by the Juju docs): see docs/API_REFERENCE.md. In particular
  the connection exploit itself is not observable; only its visible effects (ping, gap, timing)
  are measured.

  CONFIGURATION (all optional; invalid values are reported and ignored)
    1. edit USER_CONFIG below, or
    2. before running this script:  getgenv().JHC_CONFIG = {{ scope = "target", ... }}
    3. set flags jhc_cfg_<key> through another addon.
  See src/config.lua for every key.
]]

local USER_CONFIG = {{
  -- weapon_aliases = {{ "doublebarrel", "dbsg" }},   -- letters only, matched against the tool name
  -- scope = "auto",                                  -- "auto" | "target" | "all"
  -- hud = true,
}}
do
  local ok, g = pcall(function() return getgenv and getgenv() end)
  if ok and type(g) == "table" and type(g.JHC_CONFIG) == "table" then
    for k, v in pairs(g.JHC_CONFIG) do USER_CONFIG[k] = v end
  end
end

local __defs, __cache = {{}}, {{}}
local function __require(name)
  local cached = __cache[name]
  if cached ~= nil then return cached end
  local def = __defs[name]
  if not def then error("jhc bundle: unknown module " .. tostring(name)) end
  local mod = def(__require)
  __cache[name] = mod
  return mod
end

"""

FOOTER = """
return __require("main").start(USER_CONFIG)
"""


def main():
    with open(os.path.join(ROOT, "src", "config.lua"), encoding="utf-8") as fh:
        m = re.search(r'C\.VERSION\s*=\s*"([^"]+)"', fh.read())
    version = m.group(1) if m else "?"
    out = [HEADER.format(version=version)]
    for name in ORDER:
        path = os.path.join(ROOT, "src", name + ".lua")
        with open(path, encoding="utf-8") as fh:
            body = fh.read().rstrip() + "\n"
        out.append('__defs["%s"] = function(require)\n%s\nend\n\n' % (name, body))
    out.append(FOOTER)
    dist = os.path.join(ROOT, "dist")
    os.makedirs(dist, exist_ok=True)
    target = os.path.join(dist, "jhc_hood_customs.lua")
    with open(target, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("".join(out))
    size = os.path.getsize(target)
    lines = sum(1 for _ in open(target, encoding="utf-8"))
    print("wrote %s  (%d bytes, %d lines, v%s)" % (os.path.relpath(target, ROOT), size, lines, version))


if __name__ == "__main__":
    sys.exit(main())
