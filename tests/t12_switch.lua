local T = require("tf")
local H = require("harness")
local Signal = H.Mock.Signal

T.suite("12 Weapon switching")

-- A weapon change no longer invalidates a shot: once the bullet has left, what you are holding
-- does not decide whether it hit. (Live: that rule discarded every Double Barrel shot.)
T.test("switching weapon mid-window still resolves the shot, and records the switch", function()
  local c = H.standard()
  local rev = c.g:give_tool(c.me, "[Revolver]")
  H.shoot(c)
  H.run(c, 0.05)
  c.g:unequip(c.me, c.tool)
  c.g:equip(c.me, rev)
  H.settle(c)
  local s = H.stats(c)
  T.eq(s.misses, 1, "a clean miss, not thrown away")
  T.eq(s.unconfirmed, 0)
  T.is_nil(c.inst.engine.reasons.weapon_changed)
  T.eq(c.inst.engine.counters.weapon_switches, 1)
  T.eq(c.inst.engine.counters.shots_spanning_switch, 1)
  T.contains(c.inst.report(), "shots still in flight across one=1")
  H.check_invariant(c, T)
end)

T.test("a hit that lands after the weapon changed is still credited", function()
  local c = H.standard()
  local rev = c.g:give_tool(c.me, "[Revolver]")
  H.shoot(c)
  H.damage_after(c, c.enemies[1], 0.12, 20)
  H.run(c, 0.05)
  c.g:unequip(c.me, c.tool); c.g:equip(c.me, rev)
  H.settle(c)
  T.eq(H.stats(c).hits, 1)
  T.eq(H.stats(c, "weapon:doublebarrelsg").hits, 1, "credited to the weapon that fired it")
end)

T.test("the real Double Barrel pattern: fire, tool is re-parented, confirmation still lands", function()
  local c = H.standard({ tool_name = "[DoubleBarrel]" })
  -- a gun shot through the bullet signal
  c.J.signals.on_player_bullet_fired:Fire({ Name = "BULLET_RAYS" }, { Name = "GunBeam" }, nil, false)
  c.J.signals.on_player_bullet_fired:Fire({ Name = "BULLET_RAYS" }, { Name = "GunBeam" }, nil, false)
  H.run(c, 0.03)
  -- the game removes and re-adds the tool (what made every live DBS shot unconfirmed)
  local tool = c.tool
  c.g:unequip(c.me, tool)
  c.g:equip(c.me, tool)
  c.sim.task.delay(0.15, function()
    c.J.signals.on_local_bullet_confirmed:Fire(c.enemies[1], { Name = "Head" }, "-85")
  end)
  H.settle(c)
  local s = H.stats(c, "weapon:doublebarrel")
  T.eq(s.attempted, 1)
  T.eq(s.hits, 1, "the Double Barrel shot must be confirmed, not discarded")
  T.eq(s.unconfirmed, 0)
  T.eq(s.confirmed_hits, 1)
  H.check_invariant(c, T)
end)

T.test("damage after a switch is still credited to the weapon that fired", function()
  local c = H.standard()
  local rev = c.g:give_tool(c.me, "[Revolver]")
  H.shoot_hit(c, c.enemies[1], 0.12, 20)
  H.run(c, 0.05)
  c.g:unequip(c.me, c.tool)
  c.g:equip(c.me, rev)
  H.settle(c)
  T.eq(H.stats(c, "weapon:doublebarrelsg").hits, 1)
  T.eq(H.stats(c, "weapon:revolver").attempted, 0)
end)

T.test("the previous tool is inert after a switch", function()
  local c = H.standard()
  local rev = c.g:give_tool(c.me, "[Revolver]")
  c.g:unequip(c.me, c.tool)
  c.g:equip(c.me, rev)
  H.shoot(c)                                    -- old tool fires: nobody listens
  H.settle(c)
  T.eq(H.stats(c).attempted, 0)
  H.shoot(c, rev)
  H.settle(c)
  T.eq(H.stats(c, "weapon:revolver").attempted, 1)
end)

T.test("new tool appears BEFORE the old one leaves (reverse ordering) -> still correct", function()
  local c = H.standard()
  local rev = c.g:give_tool(c.me, "[Revolver]")
  c.g:equip(c.me, rev)                          -- ChildAdded first, both in the character now
  T.eq(c.inst.world.current.tool, rev)
  c.g:unequip(c.me, c.tool)                     -- ChildRemoved for the OLD tool afterwards
  T.eq(c.inst.world.current.tool, rev, "late removal of the old tool must not clear the new one")
  T.eq(c.tool.Activated.live, 0)
  T.eq(rev.Activated.live, 1)
end)

T.test("destroying the equipped tool clears the state but still resolves the shot", function()
  local c = H.standard()
  H.shoot(c)
  H.run(c, 0.05)
  c.tool:Destroy()
  T.is_nil(c.inst.world.current)
  H.settle(c)
  T.eq(H.stats(c).misses, 1)
  T.eq(c.inst.engine.counters.weapon_switches, 1)
  T.eq(c.tool.Activated.live, 0, "the destroyed tool is still released")
end)

T.test("damage arriving after the tool was destroyed is still a hit", function()
  local c = H.standard()
  H.shoot(c)
  H.damage_after(c, c.enemies[1], 0.12, 20)
  H.run(c, 0.05)
  c.tool:Destroy()
  H.settle(c)
  T.eq(H.stats(c).hits, 1)
end)

T.test("equipping a second tool before the old one leaves still resolves the shot", function()
  local c = H.standard()
  H.shoot(c)
  H.run(c, 0.05)
  local rev = c.g:give_tool(c.me, "[Revolver]")
  c.g:equip(c.me, rev)            -- ChildAdded while the old tool is still on the character
  H.settle(c)
  local st = H.stats(c)
  T.eq(st.misses, 1, "the in-flight shot must still be judged")
  T.eq(st.unconfirmed, 0)
  T.eq(c.inst.engine.counters.weapon_switches, 1)
  H.check_invariant(c, T)
end)

T.test("a switch disables the not_fired rule: the old weapon's ammo is no longer observable", function()
  local c = H.standard({ ammo = 2 })
  H.shoot(c)                       -- calibrating shot: the counter is seen to drop
  c.tool.ammo:SetValue(1)
  H.settle(c, 1)
  c.tool.ammo:SetValue(2)
  T.ok(c.inst.world.current.ammo_validated)
  local rev = c.g:give_tool(c.me, "[Revolver]")
  H.shoot(c)                       -- this one shows no decrement ...
  H.run(c, 0.05)
  c.g:unequip(c.me, c.tool)        -- ... because we switched away mid-window
  c.g:equip(c.me, rev)
  H.settle(c)
  local st = H.stats(c)
  T.eq(st.not_fired, 0, "must not claim 'did not fire' once the ammo is out of sight")
  T.eq(st.misses, 2)
  H.check_invariant(c, T)
end)

T.test("respawn and death DO still invalidate (the character state really changed)", function()
  local c = H.standard()
  H.shoot(c)
  H.run(c, 0.05)
  c.g:despawn(c.me)
  H.settle(c)
  T.eq(H.stats(c).misses, 0)
  T.eq(c.inst.engine.reasons.respawn, 1)
end)

T.test("100 rapid switches between two tools: one listener at most, no leak", function()
  local c = H.standard()
  local a = c.tool
  local b = c.g:give_tool(c.me, "[Revolver]")
  local base = Signal.live_total
  for i = 1, 100 do
    c.g:unequip(c.me, a); c.g:equip(c.me, b)
    c.g:unequip(c.me, b); c.g:equip(c.me, a)
  end
  T.eq(Signal.live_total, base)
  T.eq(a.Activated.live, 1); T.eq(b.Activated.live, 0)
  T.eq(c.inst.world.current.tool, a)
end)

T.test("switching to a non-DBS weapon and back drives Auto Mode ARMED <-> ACTIVE", function()
  local c = H.standard()
  c.J.user_set("Auto Mode", "Auto Mode DBS", true)
  local rev = c.g:give_tool(c.me, "[Revolver]")
  c.g:unequip(c.me, c.tool); c.g:equip(c.me, rev)
  T.eq(c.inst.auto.state, "ARMED")
  c.g:unequip(c.me, rev); c.g:equip(c.me, c.tool)
  T.eq(c.inst.auto.state, "ACTIVE")
end)

T.test("per-weapon statistics survive switching", function()
  local c = H.standard({ enemies = 1 })
  local rev = c.g:give_tool(c.me, "[Revolver]")
  for i = 1, 3 do
    H.shoot_hit(c, c.enemies[1], 0.07, 2); H.run(c, 1)
    c.g:unequip(c.me, c.tool); c.g:equip(c.me, rev)
    H.shoot(c, rev); H.run(c, 1)
    c.g:unequip(c.me, rev); c.g:equip(c.me, c.tool)
  end
  local d, r = H.stats(c, "weapon:doublebarrelsg"), H.stats(c, "weapon:revolver")
  T.eq(d.attempted, 3); T.eq(d.hits, 3)
  T.eq(r.attempted, 3); T.eq(r.misses, 3)
  T.eq(H.stats(c).attempted, 6)
  H.check_invariant(c, T)
end)

return true
