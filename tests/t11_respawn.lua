local T = require("tf")
local H = require("harness")
local Signal = H.Mock.Signal

T.suite("11 Respawn handling")

T.test("local respawn mid-window without damage -> unconfirmed(respawn), not a miss", function()
  local c = H.standard()
  H.shoot(c)
  H.run(c, 0.05)
  c.g:despawn(c.me)
  H.settle(c)
  local s = H.stats(c)
  T.eq(s.misses, 0); T.eq(s.unconfirmed, 1)
  T.eq(c.inst.engine.reasons.respawn, 1)
  H.check_invariant(c, T)
end)

T.test("local respawn mid-window but the damage still arrives -> hit", function()
  local c = H.standard()
  H.shoot_hit(c, c.enemies[1], 0.12, 20)
  H.run(c, 0.05)
  c.g:despawn(c.me)
  H.settle(c)
  T.eq(H.stats(c).hits, 1)
end)

T.test("dying (Humanoid.Died) mid-window is recorded as context 'died'", function()
  local c = H.standard()
  c.me.hum:SetHealth(50)
  H.shoot(c)
  c.me.hum:SetHealth(0)                       -- fires Died
  H.settle(c)
  T.eq(c.inst.engine.last_shot.reason, "died")
  T.eq(H.stats(c).misses, 0)
end)

T.test("after respawn a freshly equipped tool tracks shots again", function()
  local c = H.standard()
  c.g:despawn(c.me)
  c.g:spawn(c.me)
  local t2 = c.g:give_tool(c.me, "[Double-Barrel SG]")
  c.g:equip(c.me, t2)
  H.shoot_hit(c, c.enemies[1], 0.07, 10, nil)
  -- shoot_hit used c.tool (old tool, listener dropped): nothing registered
  H.settle(c)
  T.eq(H.stats(c).attempted, 0, "the OLD tool must be inert after respawn")
  H.shoot(c, t2)
  H.damage_after(c, c.enemies[1], 0.07, 10)
  H.settle(c)
  T.eq(H.stats(c).hits, 1)
  T.eq(H.stats(c).attempted, 1)
end)

T.test("respawn drops every listener of the old character and tool", function()
  local c = H.standard()
  T.eq(c.tool.Activated.live, 1)
  local char = c.me.Character
  c.g:despawn(c.me)
  T.eq(c.tool.Activated.live, 0)
  T.eq(char.ChildAdded.live, 0)
  T.eq(char.ChildRemoved.live, 0)
end)

T.test("50 respawn cycles: connection count is stable (no leak)", function()
  local c = H.standard()
  c.g:despawn(c.me); c.g:spawn(c.me)
  local base = Signal.live_total
  for i = 1, 50 do
    c.g:despawn(c.me)
    c.g:spawn(c.me)
    local t = c.g:give_tool(c.me, "[Double-Barrel SG]")
    c.g:equip(c.me, t)
  end
  c.g:despawn(c.me); c.g:spawn(c.me)
  T.eq(Signal.live_total, base, "leaked " .. (Signal.live_total - base))
end)

T.test("Auto Mode follows the respawn cycle", function()
  local c = H.standard()
  c.J.user_set("Auto Mode", "Auto Mode DBS", true)
  T.eq(c.inst.auto.state, "ACTIVE")
  c.g:despawn(c.me)
  T.eq(c.inst.auto.state, "ARMED")
  c.g:spawn(c.me)
  c.g:equip(c.me, c.g:give_tool(c.me, "[Double-Barrel SG]"))
  T.eq(c.inst.auto.state, "ACTIVE")
end)

T.test("enemy respawn: new Humanoid is hooked, old one is released, damage on the new one counts", function()
  local c = H.standard({ enemies = 1 })
  local e = c.enemies[1]
  local old_hum = e.hum
  T.eq(old_hum.HealthChanged.live, 1)
  c.g:despawn(e)
  T.eq(old_hum.HealthChanged.live, 0)
  T.eq(old_hum.Died.live, 0)
  c.g:spawn(e)
  T.eq(e.hum.HealthChanged.live, 1)
  H.shoot_hit(c, e, 0.07, 10)
  H.settle(c)
  T.eq(H.stats(c).hits, 1)
end)

T.test("enemy respawn heals to full: health INCREASE is never damage", function()
  local c = H.standard({ enemies = 1 })
  local e = c.enemies[1]
  e.hum:SetHealth(10)
  H.run(c, 1)
  c.g:despawn(e)
  c.g:spawn(e, { health = 100 })
  H.run(c, 1)
  T.eq(c.inst.engine.counters.unattributed_damage, 1, "only the original 100 -> 10 drop")
  T.eq(c.inst.engine.counters.invalid_events, 0, "the heal must not even reach the engine")
  T.eq(H.stats(c).hits, 0)
end)

T.test("enemy leaves and joins: trackers follow", function()
  local c = H.standard({ enemies = 2 })
  T.eq(c.inst.world:target_count(), 2)
  c.g:remove_player(c.enemies[2])
  T.eq(c.inst.world:target_count(), 1)
  local p = c.g:add_player("Newcomer", 300)
  c.g:spawn(p)
  T.eq(c.inst.world:target_count(), 2)
  H.shoot_hit(c, p, 0.07, 10)
  H.settle(c)
  T.eq(H.stats(c).hits, 1)
  T.eq(c.inst.engine.last_shot.victim, 300)
end)

T.test("player churn (join/leave x40) leaves no connections behind", function()
  local c = H.standard({ enemies = 1 })
  local base = Signal.live_total
  for i = 1, 40 do
    local p = c.g:add_player("Churn" .. i, 1000 + i)
    c.g:spawn(p)
    c.g:remove_player(p)
  end
  T.eq(Signal.live_total, base)
  T.eq(c.inst.world:target_count(), 1)
end)

T.test("shooting while no character exists is ignored safely", function()
  local c = H.standard()
  local tool = c.tool
  c.g:despawn(c.me)
  tool.Activated:Fire()
  H.settle(c)
  T.eq(H.stats(c).attempted, 0)
  T.eq(#c.sim.errors, 0)
end)

return true
