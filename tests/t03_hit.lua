local T = require("tf")
local H = require("harness")

T.suite("03 Hit detection")

T.test("replicated damage after a shot is a confirmed hit with measured latency", function()
  local c = H.standard()
  H.shoot_hit(c, c.enemies[1], 0.07, 20)
  H.settle(c)
  local s = H.stats(c)
  T.eq(s.attempted, 1); T.eq(s.hits, 1); T.eq(s.misses, 0); T.eq(s.unconfirmed, 0); T.eq(s.pending, 0)
  local shot = c.inst.engine.last_shot
  T.eq(shot.outcome, "hit")
  T.near(shot.latency, 0.07, 1e-6)
  T.eq(shot.victim, 101)
  T.eq(shot.damage_total, 20)
  H.check_invariant(c, T); H.clean_sim(c, T)
end)

T.test("a hit resolves immediately, it does not wait for the window to close", function()
  local c = H.standard()
  H.shoot_hit(c, c.enemies[1], 0.07, 20)
  H.run(c, 0.08)
  T.eq(H.stats(c).hits, 1)
  T.eq(c.inst.engine:pending_count(), 0)
end)

T.test("pellets of one shot (burst of HealthChanged events) count as ONE hit", function()
  local c = H.standard()
  H.shoot(c)
  for i = 0, 7 do H.damage_after(c, c.enemies[1], 0.07 + i * 0.001, 5) end
  H.settle(c)
  local s = H.stats(c)
  T.eq(s.hits, 1, "one shot, one hit")
  T.eq(s.attempted, 1)
  local shot = c.inst.engine.last_shot
  T.eq(shot.damage_events, 8)
  T.near(shot.damage_total, 40, 1e-9)
  T.near(s.damage, 40, 1e-9, "bucket damage must include later pellets")
end)

T.test("damage on any observed enemy confirms under scope=auto without a ragebot target", function()
  local c = H.standard({ enemies = 3 })
  H.shoot_hit(c, c.enemies[3], 0.08, 30)
  H.settle(c)
  T.eq(H.stats(c).hits, 1)
  T.eq(c.inst.engine.last_shot.victim, 103)
end)

T.test("healing is never a hit", function()
  local c = H.standard()
  c.enemies[1].hum:SetHealth(50)       -- earlier damage by someone else
  H.run(c, 0.5)
  H.shoot(c)
  H.damage_after(c, c.enemies[1], 0.07, -30)   -- negative damage = heal
  H.settle(c)
  T.eq(H.stats(c).hits, 0)
  T.eq(H.stats(c).misses, 1)
  T.eq(c.inst.engine.counters.invalid_events, 0, "heals must be filtered before they reach the engine")
end)

T.test("damage without any shot is never a hit", function()
  local c = H.standard()
  c.enemies[1].hum:SetHealth(70)
  H.settle(c, 1)
  T.eq(H.stats(c).hits, 0)
  T.eq(c.inst.engine.counters.unattributed_damage, 1)
end)

T.test("damage that happened BEFORE the shot is not attributed to it", function()
  local c = H.standard()
  c.enemies[1].hum:SetHealth(70)       -- other player's damage
  H.run(c, 0.01)
  H.shoot(c)
  H.settle(c)
  T.eq(H.stats(c).hits, 0)
  T.eq(H.stats(c).misses, 1)
end)

T.test("causal floor: damage faster than half a round trip cannot be this shot's", function()
  local c = H.standard({ ping = 200 })        -- floor = 0.5 * 200ms = 100ms
  H.shoot(c)
  H.damage_after(c, c.enemies[1], 0.02, 20)    -- 20ms after the shot: impossible
  H.run(c, 0.1)
  T.eq(H.stats(c).hits, 0)
  T.eq(c.inst.engine.counters.early_damage, 1)
  H.settle(c)
  T.eq(H.stats(c).misses, 1)
end)

T.test("an impossible-early event does not poison a genuine later hit", function()
  local c = H.standard({ ping = 200 })
  H.shoot(c)
  H.damage_after(c, c.enemies[1], 0.02, 20)
  H.damage_after(c, c.enemies[1], 0.22, 20)
  H.settle(c)
  T.eq(H.stats(c).hits, 1)
  T.near(c.inst.engine.last_shot.latency, 0.22, 1e-6)
end)

T.test("causal check can be disabled by config", function()
  local c = H.standard({ ping = 200, config = { causal_check = false } })
  H.shoot(c)
  H.damage_after(c, c.enemies[1], 0.02, 20)
  H.settle(c)
  T.eq(H.stats(c).hits, 1)
end)

T.test("killing blow: HealthChanged(0) then Died is still ONE hit", function()
  local c = H.standard()
  c.enemies[1].hum:SetHealth(20)
  H.run(c, 0.5)
  H.shoot_hit(c, c.enemies[1], 0.07, 20)
  H.settle(c)
  T.eq(H.stats(c).hits, 1)
  T.near(H.stats(c).damage, 20, 1e-9)
end)

T.test("Died without a preceding HealthChanged still registers once", function()
  local c = H.standard()
  H.shoot(c)
  c.sim.task.delay(0.07, function() c.enemies[1].hum.Died:Fire() end)
  H.settle(c)
  T.eq(H.stats(c).hits, 1)
end)

T.test("a Humanoid that appears after the character model is picked up", function()
  local c = H.boot({ pre = function(x)
    x.J.ping = 60
    x.g:spawn(x.me)
    local p = x.g:add_player("Slow", 200)
    x.g:spawn(p, { late_humanoid = true })
    x.enemies[1] = p
    x.tool = x.g:give_tool(x.me, "[Double-Barrel SG]")
    x.g:equip(x.me, x.tool)
  end })
  -- before the Humanoid exists the player is not observable
  H.shoot(c); H.settle(c)
  T.eq(c.inst.engine.last_shot.reason, "no_observable_target")
  c.g:add_humanoid_late(c.enemies[1])
  H.run(c, 1)
  H.shoot_hit(c, c.enemies[1], 0.07, 20)
  H.settle(c)
  T.eq(H.stats(c).hits, 1)
end)

T.test("oldest pending shot gets the damage (FIFO) and later one is not double-credited", function()
  local c = H.standard()
  H.shoot(c)
  H.run(c, 0.1)
  H.shoot(c)
  H.damage_after(c, c.enemies[1], 0.05, 20)    -- t=0.15: both windows contain it
  H.settle(c)
  local s = H.stats(c)
  T.eq(s.attempted, 2)
  T.eq(s.hits, 1, "one damage burst can confirm only one shot")
  T.eq(s.unconfirmed, 1, "the other is ambiguous, not a miss and not a second hit")
  H.check_invariant(c, T)
end)

return true
