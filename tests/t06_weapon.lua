local T = require("tf")
local H = require("harness")
local Weapon = require("weapon")
local Config = require("config")

T.suite("06 Weapon detection")

T.test("a tool already equipped when the addon loads is picked up", function()
  local c = H.standard()
  local cur = c.inst.world.current
  T.ok(cur, "no current weapon")
  T.eq(cur.tool, c.tool)
  T.eq(cur.weapon.key, "doublebarrelsg")
  T.eq(cur.weapon.name, "[Double-Barrel SG]")
end)

T.test("equipping after load is detected; unequipping clears it", function()
  local c = H.standard({ tool = false })
  T.is_nil(c.inst.world.current)
  local rev = c.g:give_tool(c.me, "[Revolver]")
  T.is_nil(c.inst.world.current, "backpack tools are not equipped")
  c.g:equip(c.me, rev)
  T.eq(c.inst.world.current.weapon.key, "revolver")
  T.falsy(c.inst.world.current.weapon.is_dbs)
  c.g:unequip(c.me, rev)
  T.is_nil(c.inst.world.current)
end)

T.test("non-Tool children of the character are ignored", function()
  local c = H.standard({ tool = false })
  local f = H.Mock.Instance.new("Folder", "Accessory")
  f:SetParent(c.me.Character)
  T.is_nil(c.inst.world.current)
end)

T.test("duplicate ChildAdded for the same tool does not stack connections", function()
  local c = H.standard()
  T.eq(c.tool.Activated.live, 1)
  c.me.Character.ChildAdded:Fire(c.tool)
  c.me.Character.ChildAdded:Fire(c.tool)
  T.eq(c.tool.Activated.live, 1)
  H.shoot(c); H.settle(c)
  T.eq(H.stats(c).attempted, 1)
end)

T.test("a duplicate ChildAdded must not taint an in-flight shot with 'weapon_changed'", function()
  local c = H.standard()
  H.shoot(c)
  c.me.Character.ChildAdded:Fire(c.tool)
  H.settle(c)
  T.eq(c.inst.engine.last_shot.outcome, "miss")
  T.is_nil(c.inst.engine.reasons.weapon_changed)
end)

T.test("re-equipping the same tool repeatedly never leaves more than one listener", function()
  local c = H.standard()
  for i = 1, 20 do
    c.g:unequip(c.me, c.tool)
    T.eq(c.tool.Activated.live, 0, "listener left after unequip")
    c.g:equip(c.me, c.tool)
  end
  T.eq(c.tool.Activated.live, 1)
end)

T.test("ammo counters in the tool name do not change the weapon key", function()
  local c = H.standard({ tool_name = "[Revolver] - 6 | 6" })
  T.eq(c.inst.world.current.weapon.key, "revolver")
  H.shoot(c); H.run(c, 1)
  c.tool.Name = "[Revolver] - 5 | 6"
  H.shoot(c); H.run(c, 1)
  T.eq(H.stats(c, "weapon:revolver").attempted, 2)
  T.eq(#c.inst.engine:bucket_names(), 3, "all, mode:manual, weapon:revolver only")
end)

T.test("a tool rename that changes identity is re-identified at the next shot", function()
  local c = H.standard({ tool_name = "[Revolver]" })
  T.falsy(c.inst.auto.ctx.weapon_is_dbs)
  c.tool.Name = "[Double-Barrel SG]"
  H.shoot(c)
  T.ok(c.inst.auto.ctx.weapon_is_dbs)
  T.eq(c.inst.world.current.weapon.key, "doublebarrelsg")
end)

T.test("ammo source: numeric 'Ammo' child is found, 'MaxAmmo' is not", function()
  local c = H.standard({ ammo = 2, max_ammo = 2 })
  T.eq(c.inst.world.current.ammo_kind, "value:Ammo")
end)

T.test("ammo source: numeric attribute is found", function()
  local c = H.standard({ attr_ammo = 5 })
  T.eq(c.inst.world.current.ammo_kind, "attr:Ammo")
  H.shoot(c)
  c.tool:SetAttribute("Ammo", 4)
  H.settle(c)
  T.eq(H.stats(c).fired, 1)
  T.eq(H.stats(c).misses, 1)
end)

T.test("no ammo-like value: fire evidence is reported as unavailable, shots are still tracked", function()
  local c = H.standard()
  T.is_nil(c.inst.world.current.ammo_kind)
  H.shoot(c); H.settle(c)
  T.eq(H.stats(c).misses, 1)
  T.eq(H.stats(c).not_fired, 0)
end)

T.test("reload (ammo increase) is not a shot", function()
  local c = H.standard({ ammo = 0 })
  c.tool.ammo:SetValue(2)
  H.run(c, 1)
  T.eq(c.inst.engine.counters.fire_unmatched, 0)
  T.eq(H.stats(c).attempted, 0)
end)

T.test("Weapon.is_ammo_name: patterns match word starts/ends only, even short custom ones", function()
  local cfg = { ammo_patterns = { "mag" } }
  T.ok(Weapon.is_ammo_name("Mags", cfg))
  T.ok(Weapon.is_ammo_name("CurrentMag", cfg))
  T.falsy(Weapon.is_ammo_name("Damage", cfg), "'mag' sits in the middle of 'damage'")
  T.falsy(Weapon.is_ammo_name("Image", cfg))
end)

T.test("Weapon.identify: empty / nil / odd names never raise", function()
  local cfg = Config.new().values
  for _, nm in ipairs({ "", "   ", "123", "[]" }) do
    local w = Weapon.identify(nm, cfg)
    T.eq(w.key, "unknown"); T.falsy(w.is_dbs)
  end
  local w = Weapon.identify(nil, cfg)
  T.eq(w.key, "unknown")
  T.eq(w.name, "?")
  w = Weapon.identify(42, cfg)
  T.eq(w.key, "unknown")
end)

T.test("Weapon.is_ammo_name", function()
  local cfg = Config.new().values
  T.ok(Weapon.is_ammo_name("Ammo", cfg))
  T.ok(Weapon.is_ammo_name("CurrentClip", cfg))
  T.ok(Weapon.is_ammo_name("Shells", cfg))
  T.ok(Weapon.is_ammo_name("ammo_count", cfg))
  T.ok(Weapon.is_ammo_name("currentammo", cfg))
  T.ok(Weapon.is_ammo_name("Magazine", cfg))
  T.falsy(Weapon.is_ammo_name("MaxAmmo", cfg))
  T.falsy(Weapon.is_ammo_name("maxammo", cfg))
  T.falsy(Weapon.is_ammo_name("Max_Clip", cfg))
  T.falsy(Weapon.is_ammo_name("Damage", cfg), "Damage contains 'mag' but is not ammo")
  T.falsy(Weapon.is_ammo_name("MagicPower", cfg))
  T.falsy(Weapon.is_ammo_name("Cooldown", cfg))
  T.falsy(Weapon.is_ammo_name("", cfg))
  T.falsy(Weapon.is_ammo_name(nil, cfg))
end)

return true
